CREATE DATABASE course_app;

CREATE ROLE course_app WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD 'secure_app_pass_123';
CREATE ROLE course_analyst WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD 'secure_analyst_pass_123';

-- 2. Переключение на course_app
\connect course_app

REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA IF NOT EXISTS app AUTHORIZATION course_admin;
REVOKE ALL ON SCHEMA app FROM PUBLIC;

CREATE TABLE IF NOT EXISTS app.replication_probe (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    marker text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

GRANT CONNECT ON DATABASE course_app TO course_app, course_analyst;
GRANT USAGE ON SCHEMA app TO course_app, course_analyst;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA app TO course_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA app TO course_app;
GRANT SELECT ON ALL TABLES IN SCHEMA app TO course_analyst;

ALTER DEFAULT PRIVILEGES FOR ROLE course_admin IN SCHEMA app
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO course_app;
ALTER DEFAULT PRIVILEGES FOR ROLE course_admin IN SCHEMA app
    GRANT USAGE, SELECT ON SEQUENCES TO course_app;
ALTER DEFAULT PRIVILEGES FOR ROLE course_admin IN SCHEMA app
    GRANT SELECT ON TABLES TO course_analyst;
